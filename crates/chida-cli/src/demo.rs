pub fn blank_project(name: &str) -> ProjectFile {
    let mut project = Project::new(slug(name), name);
    let mut page = Page::new("home", "Home", "/", 1200.0, 800.0);
    page.root.children.push(Node::text_node(
        "title",
        "Title",
        40.0,
        40.0,
        500.0,
        44.0,
        name,
        32.0,
        Color::BLACK,
    ));
    project.pages.push(page);
    ProjectFile {
        project,
        database: Database::default(),
        flows: Vec::new(),
    }
}
fn slug(name: &str) -> String {
    name.to_lowercase()
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '-' })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn demo_is_valid_and_rich() {
        let d = demo_shop();
        assert!(d.validate().is_empty(), "{:?}", d.validate());
        assert_eq!(d.project.pages.len(), 2);
        assert!(d.project.total_nodes() >= 30);
        assert_eq!(d.database.tables.len(), 2);
        assert_eq!(d.flows.len(), 1);
    }
    #[test]
    fn blank_is_valid() {
        assert!(blank_project("My App").validate().is_empty());
    }
    #[test]
    fn persian_demo_is_valid_and_rtl() {
        let d = persian_project();
        assert!(d.validate().is_empty(), "{:?}", d.validate());
        assert_eq!(d.project.pages.len(), 1);
        let texts: Vec<String> = d.project.pages[0]
            .root
            .children
            .iter()
            .flat_map(|n| {
                let mut v: Vec<String> = n.text.clone().into_iter().collect();
                v.extend(n.children.iter().filter_map(|c| c.text.clone()));
                v
            })
            .collect();
        assert!(texts.iter().any(|t| t.contains("گلکده سپیدار")));
        assert!(texts.iter().any(|t| t.contains("۴۸۰۰۰۰")));
    }
}
