//! The built-in shop template used by `chida new demo`.
//! Two pages (storefront and admin), a products and orders schema with a
//! relation, seed products, and one checkout logic flow.
use crate::project_file::ProjectFile;
use chida_core::{Color, ComponentDef, Node, NodeKind, Page, Project};
use chida_db::{Column, ColumnType, Database, Relation, RelationKind, Table};
use chida_logic::{Action, CompareOp, Event, EventKind, Expr, Flow, Step};
use serde_json::{json, Map};

fn text(id: &str, x: f32, y: f32, w: f32, s: &str, size: f32, color: Color, bold: bool) -> Node {
    let mut n = Node::text_node(id, s, x, y, w, size + 10.0, s, size, color);
    n.bold = bold;
    n
}
fn card(
    id: &str,
    x: f32,
    y: f32,
    name: &str,
    price: &str,
    primary: Color,
    ink: Color,
    muted: Color,
) -> Node {
    let mut c = Node::new(id, "Product card", NodeKind::Card, x, y, 220.0, 250.0);
    c.fill = Some(Color::WHITE);
    c.corner_radius = 16.0;
    c.stroke = Some(Color::rgb(225, 230, 227));
    c.stroke_width = 1.0;
    let mut img = Node::rect(
        format!("{id}-img"),
        "Product image",
        16.0,
        16.0,
        188.0,
        110.0,
        Color::rgb(214, 237, 225),
    );
    img.corner_radius = 12.0;
    let mut buy = Node::new(
        format!("{id}-buy"),
        "Buy button",
        NodeKind::Button,
        16.0,
        196.0,
        188.0,
        38.0,
    );
    buy.fill = Some(primary);
    buy.corner_radius = 10.0;
    buy.text = Some("Add to cart".into());
    buy.font_size = 14.0;
    buy.text_color = Some(Color::WHITE);
    c.children = vec![
        img,
        text(
            &format!("{id}-name"),
            16.0,
            138.0,
            188.0,
            name,
            16.0,
            ink,
            true,
        ),
        text(
            &format!("{id}-price"),
            16.0,
            164.0,
            188.0,
            price,
            14.0,
            muted,
            false,
        ),
        buy,
    ];
    c
}

