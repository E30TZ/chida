//! chida-codegen: project in, complete Rust full-stack app out.
//!
//! The generated app is a Cargo workspace with an Axum backend (CRUD for
//! every table, register and login with salted SHA-256 password hashing,
//! marked clearly as a stub to upgrade to Argon2 before production) and a
//! Leptos frontend with one component per page. It also gets the SQL
//! schema, an OpenAPI description, a Dockerfile, a systemd unit and a
//! README with run instructions. Generated code is plain, owned source:
//! nothing in it calls back into Chida.

use chida_core::{Node, NodeKind, Project};
use chida_db::Database;
use chida_logic::Flow;
use serde_json::{json, Map, Value};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

pub fn pascal(s: &str) -> String {
    s.split(|c: char| !c.is_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + &c.as_str().to_lowercase(),
                None => String::new(),
            }
        })
        .collect()
}
pub fn snake(s: &str) -> String {
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 && !out.ends_with('_') && !out.is_empty() {
                out.push('_');
            }
            out.push(ch.to_lowercase().next().unwrap());
        } else if ch.is_alphanumeric() {
            out.push(ch);
        } else if !out.ends_with('_') && !out.is_empty() {
            out.push('_');
        }
    }
    out.trim_matches('_').to_string()
}
fn html_esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// OpenAPI 3 document describing the auto generated CRUD and auth API.
pub fn openapi(project: &Project, db: &Database) -> Value {
    let mut paths = Map::new();
    for t in &db.tables {
        let base = format!("/api/{}", t.name);
        paths.insert(base.clone(), json!({ "get": { "summary": format!("List {}", t.name), "responses": { "200": { "description": "OK" } } },
            "post": { "summary": format!("Create a {}", t.name), "responses": { "201": { "description": "Created" } } } }));
        paths.insert(format!("{base}/{{id}}"), json!({ "get": { "summary": format!("Get one {}", t.name), "responses": { "200": { "description": "OK" }, "404": { "description": "Not found" } } },
            "put": { "summary": format!("Update one {}", t.name), "responses": { "200": { "description": "OK" } } },
            "delete": { "summary": format!("Delete one {}", t.name), "responses": { "204": { "description": "Deleted" } } } }));
    }
    paths.insert("/api/auth/register".into(), json!({ "post": { "summary": "Register", "responses": { "201": { "description": "Created" } } } }));
    paths.insert("/api/auth/login".into(), json!({ "post": { "summary": "Login", "responses": { "200": { "description": "Token" }, "401": { "description": "Bad credentials" } } } }));
    json!({ "openapi": "3.0.3", "info": { "title": project.name, "version": "1.0.0" }, "paths": paths })
}

fn models_rs(db: &Database) -> String {
    let mut s = String::from("use serde::{Deserialize, Serialize};\n\n");
    for t in &db.tables {
        let _ = writeln!(
            s,
            "#[derive(Debug, Clone, Serialize, Deserialize)]\npub struct {} {{",
            pascal(&t.name)
        );
        s.push_str("    pub id: Option<i64>,\n");
        for c in &t.columns {
            if c.name != "id" {
                let ty = c.col_type.rust_type();
                if c.validation.required {
                    let _ = writeln!(s, "    pub {}: {},", snake(&c.name), ty);
                } else {
                    let _ = writeln!(s, "    pub {}: Option<{}>,", snake(&c.name), ty);
                }
            }
        }
        s.push_str("}\n\n");
    }
    s
}

fn backend_main_rs(project: &Project, db: &Database) -> String {
    let mut routes = String::new();
    for t in &db.tables {
        let n = &t.name;
        let _ = writeln!(
            routes,
            "        .route(\"/api/{n}\", get(handlers::list_{n}).post(handlers::create_{n}))"
        );
        let _ = writeln!(routes, "        .route(\"/api/{n}/{{id}}\", get(handlers::get_{n}).put(handlers::update_{n}).delete(handlers::delete_{n}))");
    }
    format!(
        r#"//! Backend for {name}, generated by Chida. Own this code freely.
//! Storage in this generated starter is an in-memory store seeded from
//! schema.sql data; swap `state.rs` for rusqlite or sqlx for durable
//! storage without changing the HTTP API.
use axum::{{routing::get, Router}};
use std::sync::{{Arc, Mutex}};

mod auth;
mod handlers;
mod models;
mod state;

pub use state::AppState;

#[tokio::main]
async fn main() {{
    let state = Arc::new(Mutex::new(AppState::seeded()));
    let app = Router::new()
        .route("/health", get(|| async {{ "ok" }}))
        .route("/api/auth/register", axum::routing::post(auth::register))
        .route("/api/auth/login", axum::routing::post(auth::login))
{routes}        .with_state(state);
    let addr = std::env::var("BIND").unwrap_or_else(|_| "127.0.0.1:3000".to_string());
    let listener = tokio::net::TcpListener::bind(&addr).await.expect("bind failed");
    println!("{name} backend listening on {{addr}}");
    axum::serve(listener, app).await.expect("server failed");
}}
"#,
        name = project.name,
        routes = routes
    )
}

fn handlers_rs(db: &Database) -> String {
    let mut s = String::from(
        r#"use axum::{extract::{Path, State}, http::StatusCode, Json};
use serde_json::{Map, Value};
use std::sync::{Arc, Mutex};
use crate::AppState;

pub type Shared = State<Arc<Mutex<AppState>>>;

fn rows(state: &AppState, table: &str) -> Vec<Map<String, Value>> { state.rows.get(table).cloned().unwrap_or_default() }

"#,
    );
    for t in &db.tables {
        let n = &t.name;
        let _ = writeln!(
            s,
            r#"pub async fn list_{n}(State(state): Shared) -> Json<Value> {{ let g = state.lock().unwrap(); Json(Value::Array(rows(&g, "{n}").into_iter().map(Value::Object).collect())) }}
pub async fn create_{n}(State(state): Shared, Json(body): Json<Map<String, Value>>) -> (StatusCode, Json<Value>) {{
    let mut g = state.lock().unwrap(); let id = g.next_id("{n}");
    let mut row = body; row.insert("id".into(), Value::from(id));
    g.rows.entry("{n}".into()).or_default().push(row.clone());
    (StatusCode::CREATED, Json(Value::Object(row)))
}}
pub async fn get_{n}(State(state): Shared, Path(id): Path<i64>) -> Result<Json<Value>, StatusCode> {{
    let g = state.lock().unwrap();
    rows(&g, "{n}").into_iter().find(|r| r.get("id").and_then(|v| v.as_i64()) == Some(id)).map(|r| Json(Value::Object(r))).ok_or(StatusCode::NOT_FOUND)
}}
pub async fn update_{n}(State(state): Shared, Path(id): Path<i64>, Json(body): Json<Map<String, Value>>) -> Result<Json<Value>, StatusCode> {{
    let mut g = state.lock().unwrap(); let all = g.rows.entry("{n}".into()).or_default();
    let row = all.iter_mut().find(|r| r.get("id").and_then(|v| v.as_i64()) == Some(id)).ok_or(StatusCode::NOT_FOUND)?;
    for (k, v) in body {{ if k != "id" {{ row.insert(k, v); }} }}
    Ok(Json(Value::Object(row.clone())))
}}
pub async fn delete_{n}(State(state): Shared, Path(id): Path<i64>) -> StatusCode {{
    let mut g = state.lock().unwrap();
    if let Some(all) = g.rows.get_mut("{n}") {{ all.retain(|r| r.get("id").and_then(|v| v.as_i64()) != Some(id)); }}
    StatusCode::NO_CONTENT
}}
"#
        );
    }
    s
}

fn state_rs(db: &Database) -> String {
    let mut seeds = String::new();
    for t in &db.tables {
        if !t.seed_rows.is_empty() {
            let rows_json =
                Value::Array(t.seed_rows.iter().cloned().map(Value::Object).collect()).to_string();
            let _ = writeln!(
                seeds,
                "        s.insert_seed(\"{}\", r#\"{}\"#);",
                t.name, rows_json
            );
        }
    }
    format!(
        r#"use serde_json::{{Map, Value}};
use std::collections::BTreeMap;

#[derive(Default)]
pub struct AppState {{
    pub rows: BTreeMap<String, Vec<Map<String, Value>>>,
    pub users: Vec<Map<String, Value>>,
    counters: BTreeMap<String, i64>,
}}

impl AppState {{
    pub fn seeded() -> Self {{
        let mut s = Self::default();
{seeds}        s
    }}
    pub fn next_id(&mut self, table: &str) -> i64 {{
        let current_max = self.rows.get(table).map(|rs| rs.iter().filter_map(|r| r.get("id").and_then(|v| v.as_i64())).max().unwrap_or(0)).unwrap_or(0);
        let e = self.counters.entry(table.to_string()).or_insert(current_max);
        *e += 1; *e
    }}
    fn insert_seed(&mut self, table: &str, json_rows: &str) {{
        if let Ok(Value::Array(items)) = serde_json::from_str::<Value>(json_rows) {{
            let mut next = 1i64;
            for item in items {{ if let Value::Object(mut m) = item {{ if !m.contains_key("id") {{ m.insert("id".into(), Value::from(next)); }} next += 1; self.rows.entry(table.to_string()).or_default().push(m); }} }}
        }}
    }}
}}
"#
    )
}

const AUTH_RS: &str = r#"//! Register and login. Passwords are hashed with salted SHA-256.
//! STUB: upgrade to Argon2id (the `argon2` crate) before real production use.
use axum::{extract::State, http::StatusCode, Json};
use serde::Deserialize;
use serde_json::{json, Map, Value};
use sha2::{Digest, Sha256};
use std::sync::{Arc, Mutex};
use crate::AppState;

pub type Shared = State<Arc<Mutex<AppState>>>;

#[derive(Deserialize)]
pub struct Credentials { pub email: String, pub password: String }

fn hash_password(password: &str, salt: &str) -> String {
    let mut h = Sha256::new();
    h.update(salt.as_bytes()); h.update(b":"); h.update(password.as_bytes());
    format!("{salt}${:x}", h.finalize())
}
fn verify(password: &str, stored: &str) -> bool {
    let Some((salt, _)) = stored.split_once('$') else { return false; };
    hash_password(password, salt) == stored
}
fn salt_for(email: &str) -> String {
    let mut h = Sha256::new(); h.update(email.as_bytes()); h.update(b"chida-salt");
    format!("{:x}", h.finalize())[..16].to_string()
}

pub async fn register(State(state): Shared, Json(c): Json<Credentials>) -> (StatusCode, Json<Value>) {
    if c.email.trim().is_empty() || c.password.len() < 8 { return (StatusCode::BAD_REQUEST, Json(json!({"error": "email and a password of 8+ characters are required"}))); }
    let mut g = state.lock().unwrap();
    if g.users.iter().any(|u| u.get("email").and_then(|v| v.as_str()) == Some(c.email.as_str())) {
        return (StatusCode::CONFLICT, Json(json!({"error": "email already registered"})));
    }
    let mut user = Map::new();
    user.insert("email".into(), Value::String(c.email.clone()));
    user.insert("password_hash".into(), Value::String(hash_password(&c.password, &salt_for(&c.email))));
    user.insert("role".into(), Value::String("user".into()));
    g.users.push(user);
    (StatusCode::CREATED, Json(json!({"email": c.email})))
}

pub async fn login(State(state): Shared, Json(c): Json<Credentials>) -> (StatusCode, Json<Value>) {
    let g = state.lock().unwrap();
    let ok = g.users.iter().find(|u| u.get("email").and_then(|v| v.as_str()) == Some(c.email.as_str()))
        .map(|u| u.get("password_hash").and_then(|v| v.as_str()).map(|h| verify(&c.password, h)).unwrap_or(false)).unwrap_or(false);
    if !ok { return (StatusCode::UNAUTHORIZED, Json(json!({"error": "bad credentials"}))); }
    // Token stub: a hash of the email. Replace with signed JWT or server
    // sessions for real production use.
    let mut h = Sha256::new(); h.update(c.email.as_bytes()); h.update(b"token");
    (StatusCode::OK, Json(json!({"token": format!("{:x}", h.finalize()), "email": c.email})))
}
"#;

pub fn interaction_href(node: &Node, trigger: &str) -> Option<String> {
    let raw = node.props.get("interactions")?;
    for line in raw.lines() {
        let mut parts = line.splitn(3, '|');
        if parts.next() == Some(trigger) {
            let kind = parts.next()?;
            let target = parts.next()?;
            return Some(match kind {
                "page" => format!("#{}", route_anchor(target)),
                "url" => target.to_string(),
                _ => continue,
            });
        }
    }
    None
}

pub fn route_anchor(route: &str) -> String {
    let cleaned: String = route
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '-' })
        .collect();
    format!("route-{}", cleaned.trim_matches('-'))
}

fn shadow_css(node: &Node) -> String {
    if !node.shadows.iter().any(|s| s.enabled) {
        return String::new();
    }
    let parts: Vec<String> = node
        .shadows
        .iter()
        .filter(|s| s.enabled)
        .map(|s| {
            let a = (s.color.a as f32 / 255.0) * s.opacity.clamp(0.0, 1.0);
            format!(
                "{}px {}px {}px rgba({},{},{},{:.3})",
                s.x, s.y, s.blur, s.color.r, s.color.g, s.color.b, a
            )
        })
        .collect();
    format!("box-shadow:{};", parts.join(","))
}

fn node_style(node: &Node) -> String {
    let mut style = format!(
        "position:absolute;left:{}px;top:{}px;width:{}px;height:{}px;border-radius:{}px;",
        node.x, node.y, node.width, node.height, node.corner_radius
    );
    if let Some(g) = &node.fill_gradient {
        style.push_str(&format!("background:{};", g.css()));
    } else if let Some(c) = node.fill {
        style.push_str(&format!("background:{};", c.to_hex()));
    }
    if let Some(c) = node.stroke {
        if node.stroke_width > 0.0 {
            style.push_str(&format!("border:{}px solid {};", node.stroke_width, c.to_hex()));
        }
    }
    style.push_str(&shadow_css(node));
    if node.opacity < 1.0 {
        style.push_str(&format!("opacity:{};", node.opacity));
    }
    if node.blur_radius > 0.0 {
        style.push_str(&format!("filter:blur({}px);", node.blur_radius));
    }
    if node.background_blur > 0.0 {
        style.push_str(&format!(
            "backdrop-filter:blur({}px);-webkit-backdrop-filter:blur({}px);",
            node.background_blur, node.background_blur
        ));
    }
    style
}

fn node_svg_inner(node: &Node) -> Option<String> {
    if !matches!(node.kind, NodeKind::Path | NodeKind::Arrow) {
        return None;
    }
    let fill = node.fill.map(|c| c.to_hex()).unwrap_or_else(|| "none".into());
    let stroke = node
        .stroke
        .map(|c| c.to_hex())
        .unwrap_or_else(|| fill.clone());
    if node.kind == NodeKind::Arrow {
        let head = node.arrow_head_points()?;
        let start = node.path_points.first()?;
        let end = node.path_points.get(1)?;
        return Some(format!(
            "<svg viewBox=\"0 0 {} {}\" width=\"100%\" height=\"100%\"><path d=\"M {} {} L {} {}\" fill=\"none\" stroke=\"{}\" stroke-width=\"{}\"/><path d=\"M {} {} L {} {} L {} {} Z\" fill=\"{}\"/></svg>",
            node.width,
            node.height,
            start.x,
            start.y,
            end.x,
            end.y,
            stroke,
            node.stroke_width.max(1.5),
            head[0].0,
            head[0].1,
            head[1].0,
            head[1].1,
            head[2].0,
            head[2].1,
            stroke
        ));
    }
    Some(format!(
        "<svg viewBox=\"0 0 {} {}\" width=\"100%\" height=\"100%\"><path d=\"{}\" fill=\"{}\" stroke=\"{}\" stroke-width=\"{}\"/></svg>",
        node.width,
        node.height,
        node.path_d(0.0, 0.0),
        fill,
        stroke,
        node.stroke_width
    ))
}

fn node_to_leptos(node: &Node, indent: usize) -> String {
    let pad = " ".repeat(indent);
    let style = node_style(node);
    let text = node.text.as_deref().unwrap_or("");
    let mut children = String::new();
    for ch in &node.children {
        children.push_str(&node_to_leptos(ch, indent + 4));
    }
    let rendered = match node.kind {
        NodeKind::Button => format!(
            "{pad}<button style=\"{style}\">{}{}</button>\n",
            html_esc(text),
            children
        ),
        NodeKind::Input => format!(
            "{pad}<input style=\"{style}\" placeholder=\"{}\" />\n",
            html_esc(
                node.props
                    .get("placeholder")
                    .map(|s| s.as_str())
                    .unwrap_or(text)
            )
        ),
        NodeKind::Text => format!(
            "{pad}<span style=\"{style}color:{};font-size:{}px;\">{}</span>\n",
            node.text_color.unwrap_or(chida_core::Color::BLACK).to_hex(),
            node.font_size,
            html_esc(text)
        ),
        NodeKind::Path | NodeKind::Arrow => format!(
            "{pad}<div style=\"{style}\">{}</div>\n",
            node_svg_inner(node).unwrap_or_default()
        ),
        _ => format!(
            "{pad}<div style=\"{style}\">{}{}</div>\n",
            html_esc(text),
            children
        ),
    };
    match interaction_href(node, "click") {
        Some(href) => format!(
            "{pad}<a href=\"{}\" style=\"display:contents;\">{}</a>",
            html_esc(&href),
            rendered.trim_start()
        ),
        None => rendered,
    }
}

fn frontend_app_rs(project: &Project) -> String {
    let mut s = String::from("use leptos::prelude::*;\n\n#[component]\npub fn App() -> impl IntoView {\n    view! {\n        <main class=\"chida-app\">\n");
    for page in &project.pages {
        let resolved = project.resolve_page(page);
        s.push_str(&format!("            <section id=\"{}\" data-route=\"{}\" style=\"position:relative;width:{}px;height:{}px;\">\n", route_anchor(&page.route), page.route, page.width, page.height));
        for child in &resolved.root.children {
            s.push_str(&node_to_leptos(child, 16));
        }
        s.push_str("            </section>\n");
    }
    s.push_str("        </main>\n    }\n}\n");
    s
}

fn static_preview(project: &Project) -> String {
    fn node_html(node: &Node) -> String {
        let style = node_style(node);
        let mut inner = if matches!(node.kind, NodeKind::Path | NodeKind::Arrow) {
            node_svg_inner(node).unwrap_or_default()
        } else {
            html_esc(node.text.as_deref().unwrap_or(""))
        };
        for ch in &node.children {
            inner.push_str(&node_html(ch));
        }
        let div = format!("<div style=\"{style}\">{inner}</div>");
        match interaction_href(node, "click") {
            Some(href) => format!("<a href=\"{}\">{div}</a>", html_esc(&href)),
            None => div,
        }
    }
    let mut sections = String::new();
    for page in &project.pages {
        let resolved = project.resolve_page(page);
        let mut body = String::new();
        for child in &resolved.root.children {
            body.push_str(&node_html(child));
        }
        let _ = write!(sections, "<h2>{} <small>{}</small></h2><div style=\"position:relative;width:{}px;height:{}px;background:{};border:1px solid #ddd;\">{}</div>",
            html_esc(&page.name), html_esc(&page.route), page.width, page.height, page.background.unwrap_or(chida_core::Color::WHITE).to_hex(), body);
    }
    format!("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>{}</title></head><body style=\"font-family:{};\">{}</body></html>",
        html_esc(&project.name), html_esc(&project.theme.font_family), sections)
}

/// Everything codegen will write, as (relative path, contents).
pub fn plan(project: &Project, db: &Database, flows: &[Flow]) -> Vec<(String, String)> {
    let slug = snake(&project.name).replace('_', "-");
    let backend_main = backend_main_rs(project, db);
    let mut files: Vec<(String, String)> = vec![
        ("Cargo.toml".into(), "[workspace]\nresolver = \"2\"\nmembers = [\"backend\", \"frontend\"]\n".into()),
        ("backend/Cargo.toml".into(), format!("[package]\nname = \"{slug}-backend\"\nversion = \"1.0.0\"\nedition = \"2021\"\n\n[dependencies]\naxum = \"0.8\"\ntokio = {{ version = \"1\", features = [\"full\"] }}\nserde = {{ version = \"1.0\", features = [\"derive\"] }}\nserde_json = \"1.0\"\nsha2 = \"0.10\"\n")),
        ("backend/src/main.rs".into(), backend_main),
        ("backend/src/handlers.rs".into(), handlers_rs(db)),
        ("backend/src/auth.rs".into(), AUTH_RS.into()),
        ("backend/src/state.rs".into(), state_rs(db)),
        ("backend/src/models.rs".into(), models_rs(db)),
        ("frontend/Cargo.toml".into(), format!("[package]\nname = \"{slug}-frontend\"\nversion = \"1.0.0\"\nedition = \"2021\"\n\n[dependencies]\nleptos = {{ version = \"0.8\", features = [\"csr\"] }}\n")),
        ("frontend/src/app.rs".into(), frontend_app_rs(project)),
        ("frontend/src/main.rs".into(), "mod app;\nuse app::App;\nfn main() { leptos::mount::mount_to_body(App); }\n".into()),
        ("frontend/index.html".into(), format!("<!doctype html><html><head><meta charset=\"utf-8\"><title>{}</title><link data-trunk rel=\"css\" href=\"styles.css\"></head><body></body></html>", html_esc(&project.name))),
        ("frontend/styles.css".into(), format!("body {{ font-family: {}; color: {}; background: {}; }}\n.chida-app {{ margin: 0 auto; }}\n", project.theme.font_family, project.theme.text.to_hex(), project.theme.background.to_hex())),
        ("frontend/Trunk.toml".into(), "[build]\ntarget = \"index.html\"\n".into()),
        ("schema.sql".into(), db.schema_sql()),
        ("openapi.json".into(), serde_json::to_string_pretty(&openapi(project, db)).unwrap_or_default()),
        ("flows.json".into(), serde_json::to_string_pretty(&flows).unwrap_or_default()),
        ("preview/index.html".into(), static_preview(project)),
        ("Dockerfile".into(), "FROM rust:1-slim AS build\nWORKDIR /app\nCOPY . .\nRUN cargo build --release -p backend\nFROM debian:bookworm-slim\nCOPY --from=build /app/target/release/*backend /usr/local/bin/app\nEXPOSE 3000\nCMD [\"app\"]\n".into()),
        ("deploy/app.service".into(), format!("[Unit]\nDescription={} backend generated by Chida\nAfter=network.target\n\n[Service]\nExecStart=/usr/local/bin/{}-backend\nEnvironment=BIND=127.0.0.1:3000\nRestart=on-failure\n\n[Install]\nWantedBy=multi-user.target\n", project.name, slug)),
        (".gitignore".into(), "/target\n".into()),
    ];
    let mut route_list = String::new();
    for t in &db.tables {
        let _ = writeln!(
            route_list,
            "- `GET/POST /api/{}` and `GET/PUT/DELETE /api/{}/{{id}}`",
            t.name, t.name
        );
    }
    let mut page_list = String::new();
    for p in &project.pages {
        let _ = writeln!(page_list, "- {} at `{}`", p.name, p.route);
    }
    files.push(("README.md".into(), format!("# {}\n\nGenerated by Chida from a visual project. This source is fully yours.\n\n## Run the backend\n\n```sh\ncargo run -p {}-backend\n# listens on 127.0.0.1:3000, health check at /health\n```\n\n## Run the frontend\n\n```sh\ncd frontend\ntrunk serve\n```\n\n## Static preview\n\nOpen `preview/index.html` in a browser for a dependency free preview of every page.\n\n## Pages\n\n{}\n## API\n\n{}\n- `POST /api/auth/register` then `POST /api/auth/login`\n\nSee `openapi.json` for the full API description and `schema.sql` for the database schema.\n\n## Notes\n\nPassword hashing in `backend/src/auth.rs` is a salted SHA-256 stub. Upgrade it to Argon2id before production use.\n", project.name, slug, page_list, route_list)));
    files
}

/// Write the generated app to `out_dir`. Returns the paths written.
pub fn generate(
    project: &Project,
    db: &Database,
    flows: &[Flow],
    out_dir: &Path,
) -> Result<Vec<PathBuf>, CodegenError> {
    let mut written = Vec::new();
    for (rel, contents) in plan(project, db, flows) {
        let path = out_dir.join(&rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, contents)?;
        written.push(path);
    }
    Ok(written)
}

#[derive(Debug)]
pub struct CodegenError(pub std::io::Error);
impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "codegen io error: {}", self.0)
    }
}
impl std::error::Error for CodegenError {}
impl From<std::io::Error> for CodegenError {
    fn from(e: std::io::Error) -> Self {
        Self(e)
    }
}

