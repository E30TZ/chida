#!/usr/bin/env python3
"""Regenerate crates/chida-cli/src/gen/registry.rs from packs/*.json.

Each pack file is embedded with include_str!, so the installed binary
carries every template. Run after adding, removing or renaming a pack.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PACKS_DIR = os.path.join(ROOT, "crates", "chida-cli", "src", "gen", "packs")
OUT = os.path.join(ROOT, "crates", "chida-cli", "src", "gen", "registry.rs")


def main():
    names = sorted(f[:-5] for f in os.listdir(PACKS_DIR) if f.endswith(".json"))
    if not names:
        print("no packs found in", PACKS_DIR, file=sys.stderr)
        return 1
    lines = [
        "//! Generated by tools/gen-registry.py. Do not edit by hand.",
        "",
        "/// (template id, pack JSON source).",
        "pub const PACK_SOURCES: &[(&str, &str)] = &[",
    ]
    for name in names:
        lines.append(f'    ("{name}", include_str!("packs/{name}.json")),')
    lines.append("];")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} with {len(names)} packs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
